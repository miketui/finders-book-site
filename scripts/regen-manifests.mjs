#!/usr/bin/env node
/**
 * regen-manifests.mjs — rebuild docs/FILE-TREE.md and docs/FILE-INVENTORY.md
 * from the actual tracked contents of the repository.
 *
 * Both manifests were written by hand and both drifted: as of 2026-08-15
 * FILE-TREE.md still listed 3 API routes when there were 5, and omitted
 * about.html, order.html, contact.html and every CSS/JS file added since.
 * A hand-maintained inventory of 50+ files with SHA-256 digests is a
 * manifest that will always be out of date; this makes it a build step.
 *
 *   npm run manifests
 *
 * Run it whenever files are added, removed, or renamed, and commit the
 * regenerated docs alongside the change.
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const INVENTORY = join(ROOT, 'docs/FILE-INVENTORY.md');
const TREE = join(ROOT, 'docs/FILE-TREE.md');

/** Tracked + staged files, so a manifest regenerated pre-commit is accurate. */
function trackedFiles() {
  const out = execFileSync('git', ['ls-files', '--cached', '--exclude-standard'], {
    cwd: ROOT,
    encoding: 'utf8',
  });
  return out.split('\n').map((s) => s.trim()).filter(Boolean).sort();
}

/** One-line purpose, derived from location and extension. */
function purpose(path) {
  if (path === 'gtm/autopilot/control_plane.py') {
    return 'Hardened GTM Autopilot control-plane entrypoint; enforces approvals, runtime isolation and media safety';
  }
  if (path === 'gtm/autopilot/main.py') {
    return 'Scheduled GTM Autopilot engine; loads, updates and persists GTM runtime state';
  }
  if (path === 'gtm/ebook/build_epub.py') {
    return 'Private-runtime EPUB 3 reading-edition builder and validation entrypoint';
  }
  if (path.startsWith('api/')) return 'Vercel serverless API route';
  if (path.startsWith('scripts/')) return 'Repository automation or validation script';
  if (path.startsWith('tests/')) return 'Repository automation or validation script';
  if (path.startsWith('.github/')) return 'GitHub Actions workflow';
  if (path.startsWith('assets/fonts/')) return 'Public website font asset';
  if (path.startsWith('assets/')) return 'Public website or product-preview asset';
  if (path.startsWith('docs/')) return 'Project documentation';
  if (path === 'Family-Readiness-Gap-Check.pdf') return 'Public free lead magnet';
  if (path.endsWith('.html')) return 'Public website page';
  if (path.endsWith('.css')) return 'Public website stylesheet';
  if (path.endsWith('.js') || path.endsWith('.mjs')) return 'Public website script';
  if (path.endsWith('.py')) return 'One-shot migration script';
  return 'Repository configuration or metadata';
}

/** Build a nested map from flat paths, then render it as a tree. */
function renderTree(paths) {
  const root = new Map();
  for (const p of paths) {
    const parts = p.split('/');
    let node = root;
    parts.forEach((part, i) => {
      const isFile = i === parts.length - 1;
      if (!node.has(part)) node.set(part, isFile ? null : new Map());
      if (!isFile) node = node.get(part);
    });
  }

  const lines = ['finders-book-site/'];
  const walk = (node, prefix) => {
    const entries = [...node.entries()].sort((a, b) => {
      const aDir = a[1] !== null;
      const bDir = b[1] !== null;
      if (aDir !== bDir) return aDir ? -1 : 1;
      return a[0].localeCompare(b[0]);
    });
    entries.forEach(([name, child], i) => {
      const last = i === entries.length - 1;
      lines.push(`${prefix}${last ? '└── ' : '├── '}${name}${child !== null ? '/' : ''}`);
      if (child !== null) walk(child, `${prefix}${last ? '    ' : '│   '}`);
    });
  };
  walk(root, '    ');
  return lines.join('\n');
}

const files = trackedFiles();

await writeFile(
  TREE,
  `# Repository file tree\n\nGenerated by \`npm run manifests\`. Do not edit by hand — regenerate it instead.\n\n\`\`\`text\n${renderTree(files)}\n\`\`\`\n\nThe paid Payhip deliverables are intentionally excluded. The free lead magnet remains public at the repository root to preserve its existing URL.\n`,
  'utf8'
);

const rows = [];
for (const path of files) {
  if (path === 'docs/FILE-INVENTORY.md') continue;
  const buf = await readFile(join(ROOT, path));
  rows.push(
    `| \`${path}\` | ${buf.length} | \`${createHash('sha256').update(buf).digest('hex')}\` | ${purpose(path)} |`
  );
}

await writeFile(
  INVENTORY,
  `# File inventory\n\nThis manifest records the exact byte size and SHA-256 digest of every committed file except this manifest itself.\n\nGenerated by \`npm run manifests\`. Do not edit by hand — regenerate it instead.\n\n| Path | Bytes | SHA-256 | Purpose |\n|---|---:|---|---|\n${rows.join('\n')}\n\n**Tracked files listed:** ${rows.length}\n\nRun \`npm run validate\` before every production merge.\n`,
  'utf8'
);

console.log(`Manifests regenerated: ${rows.length} files inventoried, ${files.length} in the tree.`);
void posix;
